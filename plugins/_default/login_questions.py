def _pick(pool: list, count: int) -> list:
    """从池子随机抽 count 道题，池子不够就允许重复"""
    if count <= 0:
        return []
    if count <= len(pool):
        return random.sample(pool, count)
    result = pool[:]
    random.shuffle(result)
    while len(result) < count:
        result.append(random.choice(result[:len(pool)]))


def get_questions(level: str, total: int) -> list:
    """
    根据等级从各难度题库按比例抽题。
    返回 [(题干, [可接受答案]), ...]，顺序已打乱。

    level: 'low' / 'medium' / 'high' / 'extreme'
    total: 需要的题目数
    """
    if total <= 0:
        return []

    ratios = _DISTRIBUTION.get(level, _DISTRIBUTION['medium'])
    easy_n = round(total * ratios[0])
    hard_n = round(total * ratios[2])
    medium_n = total - easy_n - hard_n

    questions = (
        _pick(EASY, easy_n)
        + _pick(MEDIUM, medium_n)
        + _pick(HARD, hard_n)
    )
    random.shuffle(questions)
    return questions


def check_answer(user_input: str, accepted: list) -> bool:
    def norm(s):
        return s.strip().lower().replace(' ', '').replace('　', '')
    u = norm(user_input)
    if not u:
        return False
    return any(u == norm(a) for a in accepted)